// Command preludegen writes each dialect's parsed prelude into the dialect's
// package as a Go literal, so a shell starts with the tree already built
// rather than parsing the same text on every start (#6397).
//
// Usage, from the repository root:
//
//	go run ./internal/preludegen
//
// Run it after changing a prelude or anything about how the parser reads
// one. Nothing is fetched and nothing is chosen: the text is the dialect's
// own Prelude, and the tree is what syntax.Parse makes of it under the
// dialect's own grammar. Each dialect's TestPreludeTree parses the text again
// and fails, naming this command, when the literal no longer equals it.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"runtime"
	"strings"

	"github.com/blairham/sh/dialect/bash"
	"github.com/blairham/sh/dialect/zsh"
	"github.com/blairham/sh/internal/asttree"
	"github.com/blairham/sh/syntax"
)

const header = `// SPDX-FileCopyrightText: 2026 Blair Hamilton
// SPDX-License-Identifier: Apache-2.0

// Code generated by internal/preludegen. DO NOT EDIT.

`

// accessor is written into the generated file rather than beside it, so that
// deleting the file leaves a package that still compiles. That is the way out
// when a change to the syntax package makes the old literal stop compiling:
// delete preludetree.go, and this command — which imports the dialect — can
// build and write it again.
const accessor = `
// PreludeTree is Prelude already parsed: exactly what syntax.Parse makes of
// Prelude() under Dialect(), built by the compiler rather than at every start.
// See driver.Shell.PreludeTree, and TestPreludeTree for the proof that it is
// the same tree.
func PreludeTree() *syntax.File { return preludeTree }
`

type spec struct {
	dir     string
	pkg     string
	prelude string
	dialect syntax.Dialect
	// machine is the Go constant the prelude's build-dependent word is
	// spelled with, or "" when the text does not depend on the build.
	machine string
}

func main() {
	specs := []spec{
		{"dialect/bash", "bash", bash.Prelude(), bash.Dialect(), "machineName"},
		{"dialect/zsh", "zsh", zsh.Prelude(), zsh.Dialect(), ""},
	}
	for _, s := range specs {
		if err := write(s); err != nil {
			fmt.Fprintln(os.Stderr, "preludegen:", err)
			os.Exit(1)
		}
	}
}

func write(s spec) error {
	f, err := syntax.Parse(s.prelude, s.dialect)
	if err != nil {
		return fmt.Errorf("%s: parsing the prelude: %w", s.pkg, err)
	}
	var consts []asttree.Constant
	if s.machine != "" {
		// The word as this build spells it, which is the same constant
		// expression the dialect builds its text from.
		word := runtime.GOARCH + "-" + runtime.GOOS
		if n := strings.Count(s.prelude, word); n != 1 {
			return fmt.Errorf("%s: the prelude holds %q %d times, want once", s.pkg, word, n)
		}
		consts = append(consts, asttree.Constant{At: strings.Index(s.prelude, word), Text: word, Expr: s.machine})
	}
	src, err := asttree.Emit(f, s.prelude, s.pkg, "preludeTree", header, consts)
	if err != nil {
		return fmt.Errorf("%s: %w", s.pkg, err)
	}
	src = append(src, accessor...)
	return os.WriteFile(filepath.Join(s.dir, "preludetree.go"), src, 0o644)
}
