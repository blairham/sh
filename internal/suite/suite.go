// Built is the columns that can run.
func Built() []Suite {
	var built []Suite
	for _, s := range Panel {
		if s.NotYet == "" {
			built = append(built, s)
		}
	}
	return built
}

// Find is the panel entry for a dialect name.
func Find(dialect string) (Suite, bool) {
	for _, s := range Panel {
		if s.Dialect == dialect {
			return s, true
		}
	}
	return Suite{}, false
}

// Syntax is the parser configuration a column's files are read with.
//
// It is the same [syntax.Dialect] the matching binary under cmd/ is built
// from, which is what lets the parsed figure be a statement about the binary
// while being measured with the library: the binary has no second parser.
func (s Suite) Syntax() (syntax.Dialect, bool) {
	switch s.Dialect {
	case "bash":
		return bash.Dialect(), true
	case "zsh":
		return zsh.Dialect(), true
	case "ksh":
		return ksh.Dialect(), true
	case "dash":
		return dash.Dialect(), true
	case "ash":
		return ash.Dialect(), true
	default:
		return syntax.Dialect{}, false
	}
}
